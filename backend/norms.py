"""Normative profile of a school timetable for the Republic of Kazakhstan.

Every number below keeps the source it was taken from and an honest status:
``подтверждено первоисточником`` (quoted from the acting order), ``вторичный
источник`` or ``не установлено действующим НПА`` (a school rule, not a quote).
The profile is injected as ordinary ``Rule`` records, so it works with the
existing ``rules``/``limits`` model, needs no data migration and can be edited
or switched off by the administrator.

Primary sources
---------------
1. Приказ Министра здравоохранения Республики Казахстан от 5 августа 2021 года
   № ҚР ДСМ-76 «Об утверждении Санитарных правил "Санитарно-эпидемиологические
   требования к объектам образования"», зарегистрирован в МЮ РК 06.08.2021
   № 23890. Канонический адрес: https://adilet.zan.kz/rus/docs/V2100023890
   Полный текст (серверная выдача «Әділет»):
   https://old.adilet.zan.kz/rus/docs/V2100023890
   Архивная копия первоначальной редакции:
   https://web.archive.org/web/20220525102117/https://adilet.zan.kz/rus/docs/V2100023890
   Пункты 71–75 и приложения 3–4 в консолидированной редакции сносок об
   изменениях не имеют, то есть действуют в редакции 2021 года.
2. Приказ Министра образования и науки РК от 18.03.2008 № 125 «Об утверждении
   Типовых правил проведения текущего контроля успеваемости…» (рег. № 5191) —
   https://old.adilet.zan.kz/rus/docs/V080005191_
3. Приказ Министра просвещения РК от 31.08.2022 № 385 «Типовые правила
   деятельности организаций образования» (рег. № 29329) —
   https://old.adilet.zan.kz/rus/docs/V2200029329
4. Отменённые редакции, из которых видно происхождение «школьных» правил:
   СП № 570 от 25.07.2003 (https://old.adilet.zan.kz/rus/docs/V030002478_),
   СП № 834 от 25.10.2010 (https://old.adilet.zan.kz/rus/docs/V1000006598),
   СП № 179 от 29.12.2014 (https://old.adilet.zan.kz/rus/docs/V1400010275).
5. Российские СП 2.4.3648-20 и СанПиН 2.4.2.2821-10 приводятся только как
   источник формулировок, которых в казахстанских правилах нет; они не
   выдаются за норму РК.
"""
from datetime import date

#: Дата приказа № ҚР ДСМ-76 — с неё действуют правила профиля.
ORDER_DATE = date(2021, 8, 6)
SOURCE_SANPIN = 'Приказ МЗ РК № ҚР ДСМ-76 от 05.08.2021 (adilet V2100023890)'
SOURCE_SCHOOL_RULE = 'Правило школы (действующее НПА РК значение не устанавливает)'

# --- Приложение 3 к СП № ҚР ДСМ-76: максимальная недельная учебная нагрузка.
# Дословно: «72. Недельная учебная нагрузка в общеобразовательных организациях
# не должна превышать указанных норм в приложении 3 к настоящим Санитарным
# правилам.» Строка «Максимальная учебная нагрузка»: 5 класс – 33, 6 – 33,
# 7 – 34, 8 – 36, 9 – 38, 10 – 39, 11 – 39 часов в неделю.
# Статус: подтверждено первоисточником (значения совпадают в редакции 2021 года
# и в архивном снимке 2022 года).
# Спорно и помечено явно:
#   * разбивки «пятидневная/шестидневная неделя» в тексте нет — это недельный
#     потолок, а не число уроков в расписании;
#   * по определению п. 4 нагрузка включает инвариантную И вариативную часть
#     Типового учебного плана (факультативы и консультации), поэтому сумма
#     уроков сетки может быть ниже этого потолка;
#   * с пятидневной неделей и шестью уроками в день физически помещается 30
#     часов, то есть потолок 33–39 часов достижим только при более длинном дне.
WEEKLY_MAX = {5: 33, 6: 33, 7: 34, 8: 36, 9: 38, 10: 39, 11: 39}

# --- Максимальное число уроков в день.
# Статус: действующими СП РК не установлено. Типовые правила № 385, п. 38 прямо
# относят максимальную учебную нагрузку в день к компетенции организации
# образования. Отменённая норма РК ограничивала основную школу шестью уроками:
# СП № 570 от 25.07.2003 п. 84 и СП № 179 от 29.12.2014 п. 236 — «не более пяти
# уроков в начальной школе и не более шести уроков в основной школе». Значения
# ниже — правило школы: 5–6 классы шесть уроков, 7–11 классы семь уроков.
DAILY_MAX = {5: 6, 6: 6, 7: 7, 8: 7, 9: 7, 10: 7, 11: 7}

# --- Первая смена.
# Статус: в действующих СП РК нормы нет; п. 13 СП № ҚР ДСМ-76 только допускает
# двухсменный режим. Формулировка «1, 5, 9–11 классы — первая смена» взята из
# СП 2.4.3648-20 (РФ) п. 3.4.15. В Казахстане такая норма действовала до
# 2014 года: СП № 570 от 25.07.2003, п. 82 — «В общеобразовательных
# организациях, работающих в несколько смен, учащиеся начальной школы, пятых,
# выпускных и классов углубленного обучения должны обучаться в первую смену».
# 1 классы включены в список для полноты: модель расписания работает с 5–11.
FIRST_SHIFT_GRADES = (1, 5, 9, 11)

# --- Контрольные работы.
# Статус: «не более одной контрольной работы в день» — формулировка РФ
# (СанПиН 2.4.2.2821-10 п. 10.8). Действующая норма РК мягче и говорит о СОЧ:
# приказ МОН РК № 125 от 18.03.2008, п. 13 — «Проводится не более трех СОЧ в
# один день с учетом уровня сложности учебных предметов». Значение 1 — правило
# школы, а не цитата из НПА.
TESTS_DAILY = 1

# --- Приложение 4 к СП № ҚР ДСМ-76: таблица ранжирования предметов по
# трудности. Дословные баллы: математика и государственные языки — 11,
# иностранный язык — 10, физика/химия/информатика/биология — 9, история и
# «Человек. Общество. Право» — 8, литература и родной язык — 7, естествознание,
# география, самопознание, НВП — 6, физкультура — 5, труд и технология — 4,
# черчение — 3, изобразительное искусство — 2, музыка — 1.
# Пункт 73 требует «учитывать динамику умственной работоспособности учащихся в
# течение дня и недели» и использовать эту таблицу. Статус: подтверждено
# первоисточником.
RANK_POINTS = {'math': 11, 'russian': 11, 'kazakh': 11, 'english': 10,
               'physics': 9, 'chemistry': 9, 'informatics': 9, 'biology': 9,
               'history': 8, 'literature': 7, 'science': 6, 'geography': 6,
               'pe': 5, 'technology': 4, 'drawing': 3, 'art': 2, 'music': 1}

def difficulty(points):
    """Перевод баллов приложения 4 в шкалу проекта ``Subject.difficulty`` (1–10).

    Балл 11 (математика, государственные языки) даёт 10, балл 9 — 8, балл 1 — 1.
    Границы шкалы проекта ниже исходной, поэтому перевод сжимающий; порядок
    предметов по трудности при этом сохраняется.
    """
    return max(1, min(10, points - 1))

def rules():
    """Профиль норм РК как набор ``Rule`` для демонстрационных данных.

    Администратор подтверждает профиль флагом ``settings.confirmed`` и может
    изменить любое значение или отключить правило в справочнике «Правила».
    """
    rows = []
    for grade, value in sorted(WEEKLY_MAX.items()):
        rows.append(dict(id=f'kz-weekly-{grade}', name=f'Недельная нагрузка {grade} классов (РК)', key='weekly_max', grade=grade, value=value,
            unit='часов в неделю', kind='hard', priority='critical', effective=ORDER_DATE.isoformat(), source=SOURCE_SANPIN,
            comment='Приложение 3 к СП № ҚР ДСМ-76: потолок инвариантной и вариативной части учебного плана. Разбивки по длине недели в тексте нет.'))
    for grade, value in sorted(DAILY_MAX.items()):
        rows.append(dict(id=f'kz-daily-{grade}', name=f'Уроков в день, {grade} классы', key='daily_max', grade=grade, value=value,
            unit='уроков', kind='hard', priority='high', effective=ORDER_DATE.isoformat(), source=SOURCE_SCHOOL_RULE,
            comment='Действующие СП РК число уроков в день не устанавливают; принято школой по отменённой норме (не более 6 в основной школе) и п. 38 Типовых правил № 385.'))
    for grade in FIRST_SHIFT_GRADES:
        rows.append(dict(id=f'kz-shift-{grade}', name=f'Только первая смена, {grade} классы', key='first_shift', grade=grade, value=1,
            unit='признак', kind='hard', priority='critical', effective=ORDER_DATE.isoformat(), source=SOURCE_SCHOOL_RULE,
            comment='В действующих СП РК нормы нет; формулировка СП 2.4.3648-20 (РФ) п. 3.4.15, в Казахстане действовала до 2014 года (СП № 570, п. 82). Отключите правило (значение 0), если школа её не применяет.'))
    return rows
